/**
 * @file Wallet.h
 * @brief Объявление классов Wallet (электронный кошелёк) и Owner (его владелец),
 *        а также перечисления Currency.
 */

#ifndef WALLET_H
#define WALLET_H

#include <string>

/**
 * @brief Валюта кошелька.
 *
 * Пользовательский тип данных (поле currency класса Wallet).
 */
enum class Currency
{
    RUB, ///< Российский рубль
    USD, ///< Доллар США
    EUR  ///< Евро
};

/**
 * @brief Преобразует значение Currency в читаемую строку ("RUB", "USD", "EUR").
 * @param currency Валюта.
 * @return Строковое представление валюты.
 */
std::string currencyToString(Currency currency);

/**
 * @brief Класс, описывающий владельца кошелька.
 *
 * Объект Owner хранится внутри Wallet по значению (композиция):
 * Wallet "владеет" своим Owner, и время жизни Owner в составе
 * кошелька совпадает со временем жизни самого кошелька.
 *
 * Инварианты класса:
 *  1. Имя владельца никогда не пустое (иначе подставляется "Unknown").
 *  2. Email либо не указан (пустая строка), либо содержит символ '@'
 *     с непустыми частями до и после него.
 */
class Owner
{
public:
    /**
     * @brief Конструктор по умолчанию: имя "Unknown", email не указан.
     */
    Owner();

    /**
     * @brief Конструктор с именем (email не указан).
     * @param ownerName Имя владельца. Пустое имя заменяется на "Unknown".
     */
    explicit Owner(const std::string& ownerName);

    /**
     * @brief Конструктор с именем и email.
     * @param ownerName  Имя владельца. Пустое имя заменяется на "Unknown".
     * @param ownerEmail Email. Некорректный адрес отбрасывается
     *                   (email остаётся не указанным).
     */
    Owner(const std::string& ownerName, const std::string& ownerEmail);

    /// @brief Возвращает имя владельца.
    std::string getName() const;

    /// @brief Возвращает email (пустая строка, если не указан).
    std::string getEmail() const;

    /// @brief Возвращает true, если email указан.
    bool hasEmail() const;

    /**
     * @brief Меняет email владельца.
     * @param newEmail Новый адрес. Должен быть корректным.
     * @return true, если email изменён; false, если адрес некорректен
     *         (старый email сохраняется).
     */
    bool changeEmail(const std::string& newEmail);

private:
    std::string name;   ///< Имя владельца
    std::string email;  ///< Email (пустая строка — не указан)

    /// @brief Проверяет формат email (есть '@' с непустыми частями по краям).
    static bool isValidEmail(const std::string& value);
};

/**
 * @brief Класс, моделирующий электронный кошелёк.
 *
 * Содержит внутри себя объект другого класса — Owner (композиция).
 *
 * Инварианты класса (условия корректности состояния, которые класс
 * обязан поддерживать сам, независимо от действий извне):
 *  1. balance всегда >= 0 — баланс никогда не может стать отрицательным.
 *  2. Сумма в deposit() / withdraw() / transferTo() всегда строго
 *     положительна (amount > 0); операция с нулевой или отрицательной
 *     суммой считается некорректной и отклоняется без изменения состояния.
 *  3. Операции withdraw() / transferTo() запрещены, если кошелёк
 *     заблокирован (blocked == true).
 *  4. withdraw() / transferTo() запрещены, если запрашиваемая сумма
 *     больше текущего баланса (нельзя уйти в минус).
 *  5. transferTo() разрешён только между кошельками одной валюты
 *     (конвертация валют в модели не предусмотрена).
 */
class Wallet
{
public:
    /**
     * @brief Конструктор по умолчанию.
     *
     * Создаёт кошелёк с корректным начальным состоянием: владелец
     * по умолчанию (Owner()), баланс 0, валюта RUB, счётчик операций 0, кошелёк
     * не заблокирован. Реализован через список инициализации.
     */
    Wallet();

    /**
     * @brief Параметризованный конструктор: владелец и валюта.
     * @param owner    Владелец кошелька (копируется внутрь объекта).
     * @param currency Валюта кошелька.
     *
     * Баланс устанавливается в 0. Реализован через список инициализации.
     */
    Wallet(const Owner& owner, Currency currency);

    /**
     * @brief Параметризованный конструктор: владелец, начальный баланс и валюта.
     * @param owner          Владелец кошелька (копируется внутрь объекта).
     * @param initialBalance Начальный баланс. Если передано отрицательное
     *                       значение — баланс будет установлен в 0 (класс
     *                       не допускает некорректного состояния даже
     *                       при создании объекта).
     * @param currency       Валюта кошелька.
     */
    Wallet(const Owner& owner, double initialBalance, Currency currency);

    /**
     * @brief Деструктор.
     *
     * На этом этапе не освобождает динамическую память (в классе её нет),
     * но определён явно, чтобы продемонстрировать понимание момента
     * завершения времени жизни объекта, и уменьшает статический счётчик
     * существующих объектов.
     */
    ~Wallet();

    // --- Методы чтения состояния (const — не изменяют объект) ---

    /// @brief Возвращает владельца кошелька (только для чтения).
    const Owner& getOwner() const;

    /// @brief Возвращает текущий баланс.
    double getBalance() const;

    /// @brief Возвращает валюту кошелька.
    Currency getCurrency() const;

    /// @brief Возвращает количество успешно выполненных операций.
    int getTransactionCount() const;

    /// @brief Возвращает true, если кошелёк заблокирован.
    bool isBlocked() const;

    // --- Методы, изменяющие состояние объекта ---

    /**
     * @brief Пополняет баланс кошелька.
     * @param amount Сумма пополнения. Должна быть строго положительной.
     * @return true, если операция выполнена; false, если сумма некорректна
     *         или кошелёк заблокирован.
     */
    bool deposit(double amount);

    /**
     * @brief Снимает средства с кошелька.
     * @param amount Сумма снятия. Должна быть строго положительной и не
     *               превышать текущий баланс.
     * @return true, если операция выполнена; false, если сумма некорректна,
     *         средств недостаточно или кошелёк заблокирован.
     */
    bool withdraw(double amount);

    /**
     * @brief Переводит средства с текущего кошелька на другой.
     * @param other  Кошелёк-получатель.
     * @param amount Сумма перевода.
     * @return true, если перевод выполнен успешно; false, если валюты
     *         кошельков различаются или не выполнены условия withdraw().
     *
     * Реализован через withdraw() у текущего объекта и deposit() у other —
     * демонстрирует, что объекты класса Wallet независимы друг от друга:
     * операция меняет состояние ровно двух конкретных объектов, не
     * затрагивая остальные.
     */
    bool transferTo(Wallet& other, double amount);

    /// @brief Блокирует кошелёк (снятие и переводы становятся недоступны).
    void block();

    /// @brief Снимает блокировку с кошелька.
    void unblock();

    /// @brief Выводит полную информацию о кошельке на экран.
    void printInfo() const;

    // --- Статистика по классу ---

    /// @brief Возвращает количество существующих в данный момент объектов Wallet.
    static int getObjectCount();

private:
    Owner owner;             ///< Владелец кошелька (объект другого класса)
    double balance;          ///< Текущий баланс
    Currency currency;       ///< Валюта кошелька (пользовательский тип)
    int transactionCount;    ///< Количество успешных операций
    bool blocked;             ///< Признак блокировки кошелька

    static int objectCount;  ///< Счётчик существующих объектов класса
};

#endif // WALLET_H
